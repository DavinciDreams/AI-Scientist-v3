"""Mandatory manuscript watermark inserted before every host-side LaTeX compile.

The orchestrator owns this block. It is inserted (or regenerated in place) each time
``validate_and_compile_paper`` runs, so every published ``paper.pdf`` carries the
watermark regardless of what the writing agent did to ``paper.tex``. There is
deliberately no configuration surface: text, fill, angle, and lightness are fixed.
"""

from __future__ import annotations

import os
import re
import stat
import tempfile
from pathlib import Path

WATERMARK_TEXT = "Generated by The Agentic Scientist"
WATERMARK_BLOCK_START = "% --- watermark (auto-inserted) ---"
WATERMARK_BLOCK_END = "% --- end watermark ---"

# Fixed rendering parameters; see build_watermark_block for their meaning.
_FILL = 0.8
_LIGHTNESS = 0.85

_MAX_TEX_BYTES = 8 * 1024 * 1024

DOCCLASS_RE = re.compile(r"\\documentclass\s*(\[[^\]]*\])?\s*\{[^}]*\}")
_MANAGED_BLOCK_RE = re.compile(
    r"\n?" + re.escape(WATERMARK_BLOCK_START) + r"\n.*?" + re.escape(WATERMARK_BLOCK_END) + r"\n",
    re.DOTALL,
)

class PaperWatermarkError(ValueError):
    """Raised when the mandatory watermark cannot be applied to ``paper.tex``."""


def strip_comment(line: str) -> str:
    """Return the part of a line before an unescaped ``%`` comment."""
    return re.sub(r"(?<!\\)%.*$", "", line)


def find_documentclass_end(src: str) -> int:
    """Index in ``src`` just after the (non-commented) ``\\documentclass`` command."""
    for match in DOCCLASS_RE.finditer(src):
        line_start = src.rfind("\n", 0, match.start()) + 1
        if "\\documentclass" in strip_comment(src[line_start : match.end()]):
            return match.end()
    raise PaperWatermarkError("No \\documentclass found; paper.tex must be a full LaTeX document")


def escape_latex(text: str) -> str:
    """Escape characters that are special in LaTeX text mode."""
    specials = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(specials.get(char, char) for char in text)


def build_watermark_block() -> str:
    """Return the managed preamble block that renders the watermark on every page.

    Packages load right after ``\\documentclass``; every ``\\SetWatermark*`` setting is
    applied from the kernel's ``begindocument/end`` hook, which runs after the whole
    preamble and after every ``\\AtBeginDocument`` block. ``draftwatermark`` reads its
    settings at each shipout and the last setting wins, so a preamble-level
    reconfiguration elsewhere in the manuscript cannot displace this watermark.

    The font stays at 10pt (a size every font has, so LaTeX never substitutes a
    smaller one) and ``\\SetWatermarkScale`` stretches it to span ``_FILL`` of the
    page diagonal. Measuring inside the hook sees the fonts the class and later
    packages actually select. The text runs along the page diagonal.
    """
    esc = escape_latex(WATERMARK_TEXT)
    angle_expr = r"\fpeval{atand(\paperheight/\paperwidth)}"
    return (
        "\n"
        f"{WATERMARK_BLOCK_START}\n"
        "\\usepackage{xcolor}\n"
        "\\usepackage{xfp}% \\fpeval; in the kernel since 2022, harmless on older LaTeX\n"
        "\\usepackage{draftwatermark}\n"
        "\\newlength{\\watermarkTextWidth}\n"
        "\\AddToHook{begindocument/end}{%\n"
        f"  \\SetWatermarkText{{\\normalfont {esc}}}%\n"
        "  \\SetWatermarkFontSize{10pt}%\n"
        f"  \\SetWatermarkLightness{{{_LIGHTNESS}}}%\n"
        "  \\settowidth{\\watermarkTextWidth}"
        f"{{\\normalfont\\fontsize{{10pt}}{{12pt}}\\selectfont {esc}}}%\n"
        "  \\edef\\watermarkScale{\\fpeval{"
        f"{_FILL} * sqrt(\\paperwidth**2 + \\paperheight**2) / \\watermarkTextWidth}}}}%\n"
        f"  \\edef\\watermarkAngle{{{angle_expr}}}%\n"
        "  \\SetWatermarkScale{\\watermarkScale}%\n"
        "  \\SetWatermarkAngle{\\watermarkAngle}%\n"
        "}\n"
        f"{WATERMARK_BLOCK_END}\n"
    )


def strip_managed_block(src: str) -> str:
    """Return ``src`` without the orchestrator-managed watermark block."""
    return _MANAGED_BLOCK_RE.sub("", src, count=1)


def has_managed_watermark(src: str) -> bool:
    """True if the orchestrator-managed block is present."""
    return _MANAGED_BLOCK_RE.search(src) is not None


def add_watermark(src: str) -> str:
    """Return ``src`` with exactly one current managed watermark block.

    An existing managed block is regenerated in place so edits to it never survive.
    Other watermark or shipout setups in the manuscript are left untouched; the
    block's settings run last (see ``build_watermark_block``), so they win.
    """
    block = build_watermark_block()
    if has_managed_watermark(src):
        return _MANAGED_BLOCK_RE.sub(lambda _match: block, src, count=1)
    pos = find_documentclass_end(src)
    return src[:pos] + block + src[pos:]


def _read_regular_tex(path: Path) -> str:
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0)
    try:
        descriptor = os.open(path, flags)
    except OSError as exc:
        raise PaperWatermarkError(f"Unable to open regular TeX file: {path}") from exc
    try:
        metadata = os.fstat(descriptor)
        if not stat.S_ISREG(metadata.st_mode):
            raise PaperWatermarkError(f"TeX input is not a regular file: {path}")
        if metadata.st_size > _MAX_TEX_BYTES:
            raise PaperWatermarkError(f"TeX input exceeds the watermark size limit: {path}")
        with os.fdopen(descriptor, "rb") as handle:
            descriptor = -1
            data = handle.read(_MAX_TEX_BYTES + 1)
    finally:
        if descriptor >= 0:
            os.close(descriptor)
    if len(data) > _MAX_TEX_BYTES:
        raise PaperWatermarkError(f"TeX input exceeds the watermark size limit: {path}")
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise PaperWatermarkError(f"TeX input is not valid UTF-8: {path}") from exc


def _replace_file_atomically(path: Path, content: str) -> None:
    mode = stat.S_IMODE(os.lstat(path).st_mode)
    handle = tempfile.NamedTemporaryFile(
        "w", encoding="utf-8", dir=path.parent, prefix=f".{path.name}.", suffix=".tmp", delete=False
    )
    temp_path = Path(handle.name)
    try:
        with handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temp_path, mode)
        os.replace(temp_path, path)
    except BaseException:
        temp_path.unlink(missing_ok=True)
        raise


def apply_paper_watermark(paper_dir: Path, *, tex_name: str = "paper.tex") -> bool:
    """Insert or refresh the managed watermark block in ``paper_dir/tex_name``.

    Returns True when the file changed. Raises ``PaperWatermarkError`` when the file
    is not a usable full LaTeX document.
    """
    tex_path = paper_dir / tex_name
    source = _read_regular_tex(tex_path)
    result = add_watermark(source)
    if result == source:
        return False
    _replace_file_atomically(tex_path, result)
    return True


def watermark_staged_templates(staged_writer_skill_dir: Path) -> list[Path]:
    """Insert the managed block into every staged writer-skill template ``paper.tex``.

    Staging copies template scaffolds into an agent-writable workspace; watermarking
    them there keeps checked-in templates free of generated code while the agent
    drafts from a scaffold that already carries the block. Host validation remains
    the authority that regenerates the block before any publish.
    """
    changed: list[Path] = []
    templates_dir = staged_writer_skill_dir / "templates"
    if not templates_dir.is_dir():
        return changed
    for template_tex in sorted(templates_dir.glob("*/paper.tex")):
        if apply_paper_watermark(template_tex.parent):
            changed.append(template_tex)
    return changed
