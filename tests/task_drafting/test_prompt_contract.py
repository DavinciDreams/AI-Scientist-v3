@pytest.mark.parametrize("venue", ["alife", "iclr"])
def test_paper_templates_embed_supplementary_information_after_references(venue: str) -> None:
    template = _load(S + f"write-paper/templates/{venue}/paper.tex")
    first_clearpage = template.index(r"\clearpage")
    bibliography = template.index(r"\bibliography{references}", first_clearpage)
    second_clearpage = template.index(r"\clearpage", bibliography)
    appendix = template.index(r"\appendix", second_clearpage)
    supplement = template.index(r"\section{Supplementary Information}", appendix)

    assert first_clearpage < bibliography < second_clearpage < appendix < supplement
    assert "substantive grounded content" in template
    assert r"\section{Appendix}" not in template


