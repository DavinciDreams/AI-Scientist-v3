def _load(rel_path: str) -> str:
    return (REPO_ROOT / rel_path).read_text(encoding="utf-8")


def _cases(identifier: str, paths: str | tuple[str, ...], snippets: list[str], *, normalized=False):
    paths = (paths,) if isinstance(paths, str) else paths
    return [
        pytest.param(path, snippets, normalized, id=f"{identifier}:{Path(path).name}")
        for path in paths
    ]


